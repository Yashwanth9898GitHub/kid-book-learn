  onLetterClick(letter: string) {
    const words = this.wordMap[letter] || [letter];
    const randomIndex = Math.floor(Math.random() * words.length);
    this.selectedLetter = letter;
    this.selectedWord = words[randomIndex];
    this.voiceUnavailable = !this.speech.speak(`${letter}, ${this.selectedWord}`, 'te-IN');
  }

  speakWord() {
    this.voiceUnavailable = !this.speech.speak(`${this.selectedLetter}, ${this.selectedWord}`, 'te-IN');
  }
